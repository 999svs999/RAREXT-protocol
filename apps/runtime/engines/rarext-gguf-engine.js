  /**
   * Decode one 256-value IQ grid-quant block into `out`. This is a direct
   * transliteration of ggml's dequantize_row_iq2_xxs / iq2_xs / iq2_s /
   * iq3_xxs / iq3_s / iq1_s / iq1_m, so the dequant and dot paths read the same
   * bits the same way. Grid rows are `IQ*_GRID` byte tables (from ggml-common.h).
   */
  function iqBlockFloats(type, view, base, out) {
    var l, j;
    if (type === TYPE_IQ2_XXS) {
      var dqx = f16(view.getUint16(base, true));
      for (var ib = 0; ib < 8; ib += 1) {
        var qp = base + 2 + 8 * ib;
        var aux0 = view.getUint32(qp, true);
        var aux1 = view.getUint32(qp + 4, true);
        var dbx = dqx * (0.5 + (aux1 >>> 28)) * 0.25;
        var aux8 = [
          aux0 & 255, (aux0 >>> 8) & 255, (aux0 >>> 16) & 255, (aux0 >>> 24) & 255,
          aux1 & 255, (aux1 >>> 8) & 255, (aux1 >>> 16) & 255, (aux1 >>> 24) & 255,
        ];
        for (l = 0; l < 4; l += 1) {
          var gx = aux8[l] * 8;
          var sgnx = KSIGNS_IQ2XS[(aux1 >>> (7 * l)) & 127];
          for (j = 0; j < 8; j += 1) {
            out[ib * 32 + l * 8 + j] = dbx * IQ2XXS_GRID[gx + j] * ((sgnx & KMASK_IQ2XS[j]) ? -1 : 1);
          }
        }
      }
      return out;
    }
    if (type === TYPE_IQ2_XS) {
      var dxs = f16(view.getUint16(base, true));
      var scx = base + 2 + 64;
      for (var ib2 = 0; ib2 < 8; ib2 += 1) {
        var sx = view.getUint8(scx + ib2);
        var dbx0 = dxs * (0.5 + (sx & 15)) * 0.25;
        var dbx1 = dxs * (0.5 + (sx >> 4)) * 0.25;
        for (l = 0; l < 4; l += 1) {
          var vx = view.getUint16(base + 2 + (4 * ib2 + l) * 2, true);
          var gxx = (vx & 511) * 8;
          var sgnxx = KSIGNS_IQ2XS[(vx >> 9) & 127];
          var ddx = l < 2 ? dbx0 : dbx1;
          for (j = 0; j < 8; j += 1) {
            out[ib2 * 32 + l * 8 + j] = ddx * IQ2XS_GRID[gxx + j] * ((sgnxx & KMASK_IQ2XS[j]) ? -1 : 1);
          }
        }
      }
      return out;
    }
    if (type === TYPE_IQ2_S) {
      var d2 = f16(view.getUint16(base, true));
      var qs2 = base + 2;
      var qh2 = base + 2 + 64;
      var sc2 = base + 2 + 64 + 8;
      var sg2 = base + 2 + 32;
      for (ib = 0; ib < 8; ib += 1) {
        var s2 = view.getUint8(sc2 + ib);
        var e0 = d2 * (0.5 + (s2 & 15)) * 0.25;
        var e1 = d2 * (0.5 + (s2 >> 4)) * 0.25;
        for (l = 0; l < 4; l += 1) {
          var dl2 = l < 2 ? e0 : e1;
          var idx2 =
            view.getUint8(qs2 + 4 * ib + l) |
            ((view.getUint8(qh2 + ib) << (8 - 2 * l)) & 0x300);
          var g2 = idx2 * 8;
          var sb2 = view.getUint8(sg2 + 4 * ib + l);
          for (j = 0; j < 8; j += 1) {
            out[ib * 32 + l * 8 + j] = dl2 * IQ2S_GRID[g2 + j] * ((sb2 & KMASK_IQ2XS[j]) ? -1 : 1);
          }
        }
      }
      return out;
    }
    if (type === TYPE_IQ3_XXS) {
      var d3x = f16(view.getUint16(base, true));
      var qs3x = base + 2;
      var ss3x = base + 2 + 64;
      for (ib = 0; ib < 8; ib += 1) {
        var ax = view.getUint32(ss3x + 4 * ib, true);
        var db3x = d3x * (0.5 + (ax >>> 28)) * 0.5;
        for (l = 0; l < 4; l += 1) {
          var sg3x = KSIGNS_IQ2XS[(ax >>> (7 * l)) & 127];
          var g3a = view.getUint8(qs3x + 8 * ib + 2 * l) * 4;
          var g3b = view.getUint8(qs3x + 8 * ib + 2 * l + 1) * 4;
          for (j = 0; j < 4; j += 1) {
            out[ib * 32 + l * 8 + j] = db3x * IQ3XXS_GRID[g3a + j] * ((sg3x & KMASK_IQ2XS[j]) ? -1 : 1);
            out[ib * 32 + l * 8 + j + 4] =
              db3x * IQ3XXS_GRID[g3b + j] * ((sg3x & KMASK_IQ2XS[j + 4]) ? -1 : 1);
          }
        }
      }
      return out;
    }
    if (type === TYPE_IQ3_S) {
      var d3s = f16(view.getUint16(base, true));
      var q3 = base + 2;
      var h3 = base + 2 + 64;
      var s3 = base + 2 + 64 + 8;
      var c3 = base + 2 + 64 + 8 + 32;
      var y3 = 0;
      for (var it = 0; it < 4; it += 1) {
        var scl = view.getUint8(c3 + it);
        var dv1 = d3s * (1 + 2 * (scl & 15));
        var dv2 = d3s * (1 + 2 * (scl >> 4));
        for (var half = 0; half < 2; half += 1) {
          var dv = half === 0 ? dv1 : dv2;
          var hb = view.getUint8(h3 + it * 2 + half);
          for (l = 0; l < 4; l += 1) {
            var i1 = (view.getUint8(q3 + 2 * l) | ((hb << (8 - 2 * l)) & 256)) * 4;
            var i2 = (view.getUint8(q3 + 2 * l + 1) | ((hb << (7 - 2 * l)) & 256)) * 4;
            var sb3 = view.getUint8(s3 + l);
            for (j = 0; j < 4; j += 1) {
              out[y3 + j] = dv * IQ3S_GRID[i1 + j] * ((sb3 & KMASK_IQ2XS[j]) ? -1 : 1);
              out[y3 + j + 4] = dv * IQ3S_GRID[i2 + j] * ((sb3 & KMASK_IQ2XS[j + 4]) ? -1 : 1);
            }
            y3 += 8;
          }
          q3 += 8;
          s3 += 4;
        }
      }
      return out;
    }
    if (type === TYPE_IQ1_S) {
      var d1 = f16(view.getUint16(base, true));
      var qs1 = base + 2;
      var qh1 = base + 2 + 32;
      for (ib = 0; ib < 8; ib += 1) {
        var hv = view.getUint16(qh1 + 2 * ib, true);
        var dl1 = d1 * (2 * ((hv >> 12) & 7) + 1);
        var delta1 = hv & 0x8000 ? -0.125 : 0.125;
        for (l = 0; l < 4; l += 1) {
          var idx1 = view.getUint8(qs1 + 4 * ib + l) | (((hv >> (3 * l)) & 7) << 8);
          var g1 = idx1 * 8;
          for (j = 0; j < 8; j += 1) {
            out[ib * 32 + l * 8 + j] = dl1 * (IQ1S_GRID[g1 + j] + delta1);
          }
        }
      }
      return out;
    }
    if (type === TYPE_IQ1_M) {
      var sc0 = view.getUint16(base, true);
      var sc1 = view.getUint16(base + 2, true);
      var sc2v = view.getUint16(base + 4, true);
      var sc3 = view.getUint16(base + 6, true);
      var scaleU16 =
        (sc0 >> 12) | ((sc1 >> 8) & 0x00f0) | ((sc2v >> 4) & 0x0f00) | (sc3 & 0xf000);
      var dm = f16(scaleU16);
      var qsm = base + 8;
      var qhm = base + 8 + 32;
      var scm = [sc0, sc1, sc2v, sc3];
      for (ib = 0; ib < 8; ib += 1) {
        var sh = 6 * (ib & 1);
        var dlm1 = dm * (2 * ((scm[ib >> 1] >> sh) & 7) + 1);
        var dlm2 = dm * (2 * ((scm[ib >> 1] >> (sh + 3)) & 7) + 1);
        var hb0 = view.getUint8(qhm + 2 * ib);
        var hb1 = view.getUint8(qhm + 2 * ib + 1);
        var qb = qsm + 4 * ib;
        var idxm = [
          view.getUint8(qb) | ((hb0 << 8) & 0x700),
          view.getUint8(qb + 1) | ((hb0 << 4) & 0x700),
          view.getUint8(qb + 2) | ((hb1 << 8) & 0x700),
          view.getUint8(qb + 3) | ((hb1 << 4) & 0x700),
        ];
        var delm = [
          hb0 & 0x08 ? -0.125 : 0.125,
          hb0 & 0x80 ? -0.125 : 0.125,
          hb1 & 0x08 ? -0.125 : 0.125,
          hb1 & 0x80 ? -0.125 : 0.125,
        ];
        for (l = 0; l < 4; l += 1) {
          var gm = idxm[l] * 8;
          var dlv = l < 2 ? dlm1 : dlm2;
          for (j = 0; j < 8; j += 1) {
            out[ib * 32 + l * 8 + j] = dlv * (IQ1S_GRID[gm + j] + delm[l]);
          }
        }
      }
      return out;
    }
    throw new Error("cannot decode IQ block type " + type);
  }

  /**
   * Which LongRoPE factor tensor a run of `totalLen` positions would use:
   * "long" past the model's original context, "short" otherwise, or null when
   * the model has no LongRoPE factors. Exposed so a test can assert the choice
   * directly instead of inferring it from an argmax that may not move.
   */
  function selectRopeFactorSet(gguf, arch, totalLen) {
    var longF = tensorOrNull(gguf, "blk.0.rope_factors_long.weight");
    var shortF = tensorOrNull(gguf, "blk.0.rope_factors_short.weight");
    if (longF === undefined && shortF === undefined) return null;
    var origCtx = gguf.kv[arch + ".rope.scaling.original_context_length"] || 0;
    if (origCtx > 0 && totalLen > origCtx) return longF !== undefined ? "long" : "short";
    return shortF !== undefined ? "short" : "long";
  }

  function dequantRow(model, tensor, row, out) {
    var view = model.view;
    var base = model.dataStart + tensor.offset + row * tensor.rowBytes;
    var cols = tensor.cols;
    var i;
    var block;
    switch (tensor.type) {
      case TYPE_F32:
        for (i = 0; i < cols; i += 1) out[i] = view.getFloat32(base + i * 4, true);
        return out;
      case TYPE_F16:
        for (i = 0; i < cols; i += 1) out[i] = f16(view.getUint16(base + i * 2, true));
        return out;
      case TYPE_Q4_0:
        for (block = 0; block < cols; block += 32) {
          var q4base = base + (block / 32) * 18;
          var d4 = f16(view.getUint16(q4base, true));
          for (i = 0; i < 16; i += 1) {
            var q4 = view.getUint8(q4base + 2 + i);
            out[block + i] = ((q4 & 15) - 8) * d4;
            out[block + i + 16] = ((q4 >> 4) - 8) * d4;
          }
        }
        return out;
      case TYPE_Q5_0:
        for (block = 0; block < cols; block += 32) {
          var q5base = base + (block / 32) * 22;
          var d5 = f16(view.getUint16(q5base, true));
          var qh = view.getUint32(q5base + 2, true);
          for (i = 0; i < 16; i += 1) {
            var q5 = view.getUint8(q5base + 6 + i);
            out[block + i] = (((q5 & 15) | (((qh >> i) & 1) << 4)) - 16) * d5;
            out[block + i + 16] = (((q5 >> 4) | (((qh >> (i + 16)) & 1) << 4)) - 16) * d5;
          }
        }
        return out;
      case TYPE_Q8_0:
        for (block = 0; block < cols; block += 32) {
          var q8base = base + (block / 32) * 34;
          var d8 = f16(view.getUint16(q8base, true));
          for (i = 0; i < 32; i += 1) out[block + i] = view.getInt8(q8base + 2 + i) * d8;
        }
        return out;
      case TYPE_Q4_K:
        for (var sb = 0; sb < cols; sb += 256) {
          var kbase = base + (sb / 256) * 144;
          var kd = f16(view.getUint16(kbase, true));
          var kmin = f16(view.getUint16(kbase + 2, true));
          var scales = kbase + 4;
          var qs = kbase + 16;
          var is = 0;
          var qpos = 0;
          var vpos = sb;
          for (var group = 0; group < 256; group += 64) {
            var s0 = scaleMinK4(view, scales, is);
            var s1 = scaleMinK4(view, scales, is + 1);
            var d0 = kd * s0.d;
            var m0 = kmin * s0.m;
            var d1 = kd * s1.d;
            var m1 = kmin * s1.m;
            for (i = 0; i < 32; i += 1) {
              out[vpos + i] = d0 * (view.getUint8(qs + qpos + i) & 15) - m0;
            }
            for (i = 0; i < 32; i += 1) {
              out[vpos + 32 + i] = d1 * (view.getUint8(qs + qpos + i) >> 4) - m1;
            }
            qpos += 32;
            vpos += 64;
            is += 2;
          }
        }
        return out;
      case TYPE_Q6_K:
        for (var kb = 0; kb < cols; kb += 256) {
          var q6base = base + (kb / 256) * 210;
          var q6d = f16(view.getUint16(q6base + 208, true));
          var qlBase = q6base;
          var qhBase = q6base + 128;
          var scBase = q6base + 192;
          for (var half = 0; half < 2; half += 1) {
            for (i = 0; i < 32; i += 1) {
              var idx = half * 32 + i;
              var is6 = i < 16 ? 0 : 1;
              var ql0 = view.getUint8(qlBase + idx);
              var ql1 = view.getUint8(qlBase + idx + 32);
              var qh = view.getUint8(qhBase + idx);
              var q1 = ((ql0 & 15) | (((qh >> 0) & 3) << 4)) - 32;
              var q2 = ((ql1 & 15) | (((qh >> 2) & 3) << 4)) - 32;
              var q3 = ((ql0 >> 4) | (((qh >> 4) & 3) << 4)) - 32;
              var q4 = ((ql1 >> 4) | (((qh >> 6) & 3) << 4)) - 32;
              var o = kb + half * 128 + i;
              out[o] = q6d * view.getInt8(scBase + half * 8 + is6 + 0) * q1;
              out[o + 32] = q6d * view.getInt8(scBase + half * 8 + is6 + 2) * q2;
              out[o + 64] = q6d * view.getInt8(scBase + half * 8 + is6 + 4) * q3;
              out[o + 96] = q6d * view.getInt8(scBase + half * 8 + is6 + 6) * q4;
            }
          }
        }
        return out;
      case TYPE_Q4_1:
        for (block = 0; block < cols; block += 32) {
          var q41base = base + (block / 32) * 20;
          var d41 = f16(view.getUint16(q41base, true));
          var m41 = f16(view.getUint16(q41base + 2, true));
          for (i = 0; i < 16; i += 1) {
            var q41 = view.getUint8(q41base + 4 + i);
            out[block + i] = (q41 & 15) * d41 + m41;
            out[block + i + 16] = (q41 >> 4) * d41 + m41;
          }
        }
        return out;
      case TYPE_Q5_1:
        for (block = 0; block < cols; block += 32) {
          var q51base = base + (block / 32) * 24;
          var d51 = f16(view.getUint16(q51base, true));
          var m51 = f16(view.getUint16(q51base + 2, true));
          var qh51 = view.getUint32(q51base + 4, true);
          for (i = 0; i < 16; i += 1) {
            var q51 = view.getUint8(q51base + 8 + i);
            out[block + i] = (((q51 & 15) | (((qh51 >> i) & 1) << 4))) * d51 + m51;
            out[block + i + 16] = (((q51 >> 4) | (((qh51 >> (i + 16)) & 1) << 4))) * d51 + m51;
          }
        }
        return out;
      case TYPE_Q2_K:
        for (var q2b = 0; q2b < cols; q2b += 256) {
          var q2base = base + (q2b / 256) * 84;
          var q2d = f16(view.getUint16(q2base + 80, true));
          var q2min = f16(view.getUint16(q2base + 82, true));
          var q2scales = q2base;
          var q2qs = q2base + 16;
          var q2is = 0;
          var q2qpos = 0;
          var q2vpos = q2b;
          for (var q2n = 0; q2n < 256; q2n += 128) {
            var q2shift = 0;
            for (var q2j = 0; q2j < 4; q2j += 1) {
              var q2sc = view.getUint8(q2scales + q2is);
              q2is += 1;
              var q2dl = q2d * (q2sc & 15);
              var q2ml = q2min * (q2sc >> 4);
              for (i = 0; i < 16; i += 1) {
                out[q2vpos + i] = q2dl * ((view.getUint8(q2qs + q2qpos + i) >> q2shift) & 3) - q2ml;
              }
              q2vpos += 16;
              var q2sc2 = view.getUint8(q2scales + q2is);
              q2is += 1;
              var q2dl2 = q2d * (q2sc2 & 15);
              var q2ml2 = q2min * (q2sc2 >> 4);
              for (i = 0; i < 16; i += 1) {
                out[q2vpos + i] = q2dl2 * ((view.getUint8(q2qs + q2qpos + i + 16) >> q2shift) & 3) - q2ml2;
              }
              q2vpos += 16;
              q2shift += 2;
            }
            q2qpos += 32;
          }
        }
        return out;
      case TYPE_Q3_K:
        for (var q3b = 0; q3b < cols; q3b += 256) {
          var q3base = base + (q3b / 256) * 110;
          var q3d = f16(view.getUint16(q3base + 108, true));
          var q3scales = q3Scales(view, q3base + 96);
          var q3hm = q3base;
          var q3qs = q3base + 32;
          var q3m = 1;
          var q3is = 0;
          var q3qpos = 0;
          var q3vpos = q3b;
          for (var q3n = 0; q3n < 256; q3n += 128) {
            var q3shift = 0;
            for (var q3j = 0; q3j < 4; q3j += 1) {
              var q3dl = q3d * (q3scales[q3is] - 32);
              q3is += 1;
              for (i = 0; i < 16; i += 1) {
                var q3q = (view.getUint8(q3qs + q3qpos + i) >> q3shift) & 3;
                out[q3vpos + i] = q3dl * (q3q - ((view.getUint8(q3hm + i) & q3m) ? 0 : 4));
              }
              q3vpos += 16;
              var q3dl2 = q3d * (q3scales[q3is] - 32);
              q3is += 1;
              for (i = 0; i < 16; i += 1) {
                var q3q2 = (view.getUint8(q3qs + q3qpos + i + 16) >> q3shift) & 3;
                out[q3vpos + i] = q3dl2 * (q3q2 - ((view.getUint8(q3hm + i + 16) & q3m) ? 0 : 4));
              }
              q3vpos += 16;
              q3shift += 2;
              q3m <<= 1;
            }
            q3qpos += 32;
          }
        }
        return out;
      case TYPE_Q5_K:
        for (var q5kb = 0; q5kb < cols; q5kb += 256) {
          var q5kbase = base + (q5kb / 256) * 176;
          var q5kd = f16(view.getUint16(q5kbase, true));
          var q5kmin = f16(view.getUint16(q5kbase + 2, true));
          var q5kscales = q5kbase + 4;
          var q5kqh = q5kbase + 16;
          var q5kqs = q5kbase + 48;
          var q5kis = 0;
          var q5kqpos = 0;
          var q5kvpos = q5kb;
          var q5ku1 = 1;
          var q5ku2 = 2;
          for (var q5kj = 0; q5kj < 4; q5kj += 1) {
            var q5ks0 = scaleMinK4(view, q5kscales, q5kis);
            var q5ks1 = scaleMinK4(view, q5kscales, q5kis + 1);
            var q5kd1 = q5kd * q5ks0.d;
            var q5km1 = q5kmin * q5ks0.m;
            var q5kd2 = q5kd * q5ks1.d;
            var q5km2 = q5kmin * q5ks1.m;
            for (i = 0; i < 32; i += 1) {
              var q5kql = view.getUint8(q5kqs + q5kqpos + i);
              out[q5kvpos + i] = q5kd1 * ((q5kql & 15) + ((view.getUint8(q5kqh + i) & q5ku1) ? 16 : 0)) - q5km1;
            }
            for (i = 0; i < 32; i += 1) {
              var q5kql2 = view.getUint8(q5kqs + q5kqpos + i);
              out[q5kvpos + 32 + i] = q5kd2 * ((q5kql2 >> 4) + ((view.getUint8(q5kqh + i) & q5ku2) ? 16 : 0)) - q5km2;
            }
            q5kqpos += 32;
            q5kvpos += 64;
            q5kis += 2;
            q5ku1 <<= 2;
            q5ku2 <<= 2;
          }
        }
        return out;
      case TYPE_Q8_K:
        for (var q8kb = 0; q8kb < cols; q8kb += 256) {
          var q8kbase = base + (q8kb / 256) * 292;
          var q8kd = view.getFloat32(q8kbase, true);
          for (i = 0; i < 256; i += 1) out[q8kb + i] = q8kd * view.getInt8(q8kbase + 4 + i);
        }
        return out;
      case TYPE_IQ4_NL:
        for (block = 0; block < cols; block += 32) {
          var nlbase = base + (block / 32) * 18;
          var nld = f16(view.getUint16(nlbase, true));
          for (i = 0; i < 16; i += 1) {
            var nlq = view.getUint8(nlbase + 2 + i);
            out[block + i] = nld * IQ4NL[nlq & 15];
            out[block + i + 16] = nld * IQ4NL[nlq >> 4];
          }
        }
        return out;
      case TYPE_IQ4_XS:
        for (var xs = 0; xs < cols; xs += 256) {
          var xsbase = base + (xs / 256) * 136;
          var xsd = f16(view.getUint16(xsbase, true));
          var xsH = view.getUint16(xsbase + 2, true);
          var xsL = xsbase + 4;
          var xsQ = xsbase + 8;
          for (var xsIb = 0; xsIb < 8; xsIb += 1) {
            var xsLs =
              ((view.getUint8(xsL + (xsIb >> 1)) >> (4 * (xsIb & 1))) & 15) |
              (((xsH >> (2 * xsIb)) & 3) << 4);
            var xsDl = xsd * (xsLs - 32);
            for (i = 0; i < 16; i += 1) {
              var xq = view.getUint8(xsQ + xsIb * 16 + i);
              out[xs + xsIb * 32 + i] = xsDl * IQ4NL[xq & 15];
              out[xs + xsIb * 32 + i + 16] = xsDl * IQ4NL[xq >> 4];
            }
          }
        }
        return out;
      case TYPE_IQ2_XXS:
      case TYPE_IQ2_XS:
      case TYPE_IQ2_S:
      case TYPE_IQ3_XXS:
      case TYPE_IQ3_S:
      case TYPE_IQ1_S:
      case TYPE_IQ1_M: {
        var iqBytes = BLOCK[tensor.type].bytes;
        var iqScratch = new Float32Array(256);
        for (var qx = 0; qx < cols; qx += 256) {
          iqBlockFloats(tensor.type, view, base + (qx / 256) * iqBytes, iqScratch);
          for (i = 0; i < 256; i += 1) out[qx + i] = iqScratch[i];
        }
        return out;
      }
      case TYPE_BF16:
        for (i = 0; i < cols; i += 1) out[i] = bf16(view.getUint16(base + i * 2, true));
        return out;
      default:
        throw new Error("cannot dequantize tensor type " + tensor.type);
    }
  }

  function scaleMinK4(view, base, j) {
    var qj = view.getUint8(base + j);
    if (j < 4) {
      return { d: qj & 63, m: view.getUint8(base + j + 4) & 63 };
    }
    var qj4 = view.getUint8(base + j + 4);
    return {
      d: (qj4 & 15) | (((view.getUint8(base + j - 4) >> 6) & 3) << 4),
      m: (qj4 >> 4) | (((qj >> 6) & 3) << 4),
    };
  }

  /** Dot one quantized row against a dense vector. Kept in the quant domain so a
   * 0.5B model is served without ever materializing its weights as floats. */
  function dotRow(model, tensor, row, vec) {
    var view = model.view;
    var base = model.dataStart + tensor.offset + row * tensor.rowBytes;
    var cols = tensor.cols;
    var total = 0;
    var block;
    var i;
    var sum;
    switch (tensor.type) {
      case TYPE_F32:
        for (i = 0; i < cols; i += 1) total += view.getFloat32(base + i * 4, true) * vec[i];
        return total;
      case TYPE_F16:
        for (i = 0; i < cols; i += 1) total += f16(view.getUint16(base + i * 2, true)) * vec[i];
        return total;
      case TYPE_Q4_0:
        for (block = 0; block < cols; block += 32) {
          var q4base = base + (block / 32) * 18;
          var d4 = f16(view.getUint16(q4base, true));
          sum = 0;
          for (i = 0; i < 16; i += 1) {
            var q4 = view.getUint8(q4base + 2 + i);
            sum += ((q4 & 15) - 8) * vec[block + i];
            sum += ((q4 >> 4) - 8) * vec[block + i + 16];
          }
          total += d4 * sum;
        }
        return total;
      case TYPE_Q5_0:
        for (block = 0; block < cols; block += 32) {
          var q5base = base + (block / 32) * 22;
          var d5 = f16(view.getUint16(q5base, true));
          var qh = view.getUint32(q5base + 2, true);
          sum = 0;
          for (i = 0; i < 16; i += 1) {
            var q5 = view.getUint8(q5base + 6 + i);
            sum += (((q5 & 15) | (((qh >> i) & 1) << 4)) - 16) * vec[block + i];
            sum += (((q5 >> 4) | (((qh >> (i + 16)) & 1) << 4)) - 16) * vec[block + i + 16];
          }
          total += d5 * sum;
        }
        return total;
      case TYPE_Q8_0:
        for (block = 0; block < cols; block += 32) {
          var q8base = base + (block / 32) * 34;
          var d8 = f16(view.getUint16(q8base, true));
          sum = 0;
          for (i = 0; i < 32; i += 1) sum += view.getInt8(q8base + 2 + i) * vec[block + i];
          total += d8 * sum;
        }
        return total;
      case TYPE_Q4_K:
        sum = 0;
        for (var sb = 0; sb < cols; sb += 256) {
          var kbase = base + (sb / 256) * 144;
          var kd = f16(view.getUint16(kbase, true));
          var kmin = f16(view.getUint16(kbase + 2, true));
          var scales = kbase + 4;
          var qs = kbase + 16;
          var is = 0;
          var qpos = 0;
          var vpos = sb;
          for (var group = 0; group < 256; group += 64) {
            var s0 = scaleMinK4(view, scales, is);
            var s1 = scaleMinK4(view, scales, is + 1);
            var d0 = kd * s0.d;
            var m0 = kmin * s0.m;
            var d1 = kd * s1.d;
            var m1 = kmin * s1.m;
            for (i = 0; i < 32; i += 1) {
              sum += (d0 * (view.getUint8(qs + qpos + i) & 15) - m0) * vec[vpos + i];
            }
            for (i = 0; i < 32; i += 1) {
              sum += (d1 * (view.getUint8(qs + qpos + i) >> 4) - m1) * vec[vpos + 32 + i];
            }
            qpos += 32;
            vpos += 64;
            is += 2;
          }
        }
        return total + sum;
      case TYPE_Q6_K:
        for (var kb = 0; kb < cols; kb += 256) {
          var q6base = base + (kb / 256) * 210;
          var q6d = f16(view.getUint16(q6base + 208, true));
          var qlBase = q6base;
          var qhBase = q6base + 128;
          var scBase = q6base + 192;
          for (var half = 0; half < 2; half += 1) {
            for (i = 0; i < 32; i += 1) {
              var idx = half * 32 + i;
              var is6 = i < 16 ? 0 : 1;
              var ql0 = view.getUint8(qlBase + idx);
              var ql1 = view.getUint8(qlBase + idx + 32);
              var qh = view.getUint8(qhBase + idx);
              var q1 = ((ql0 & 15) | (((qh >> 0) & 3) << 4)) - 32;
              var q2 = ((ql1 & 15) | (((qh >> 2) & 3) << 4)) - 32;
              var q3 = ((ql0 >> 4) | (((qh >> 4) & 3) << 4)) - 32;
              var q4 = ((ql1 >> 4) | (((qh >> 6) & 3) << 4)) - 32;
              var o = kb + half * 128 + i;
              total += q6d * view.getInt8(scBase + half * 8 + is6 + 0) * q1 * vec[o];
              total += q6d * view.getInt8(scBase + half * 8 + is6 + 2) * q2 * vec[o + 32];
              total += q6d * view.getInt8(scBase + half * 8 + is6 + 4) * q3 * vec[o + 64];
              total += q6d * view.getInt8(scBase + half * 8 + is6 + 6) * q4 * vec[o + 96];
            }
          }
        }
        return total;
      case TYPE_Q4_1:
        for (block = 0; block < cols; block += 32) {
          var dq41base = base + (block / 32) * 20;
          var dq41 = f16(view.getUint16(dq41base, true));
          var mq41 = f16(view.getUint16(dq41base + 2, true));
          sum = 0;
          for (i = 0; i < 16; i += 1) {
            var qq41 = view.getUint8(dq41base + 4 + i);
            sum += ((qq41 & 15) * dq41 + mq41) * vec[block + i];
            sum += ((qq41 >> 4) * dq41 + mq41) * vec[block + i + 16];
          }
          total += sum;
        }
        return total;
      case TYPE_Q5_1:
        for (block = 0; block < cols; block += 32) {
          var dq51base = base + (block / 32) * 24;
          var dq51 = f16(view.getUint16(dq51base, true));
          var mq51 = f16(view.getUint16(dq51base + 2, true));
          var qhq51 = view.getUint32(dq51base + 4, true);
          sum = 0;
          for (i = 0; i < 16; i += 1) {
            var qq51 = view.getUint8(dq51base + 8 + i);
            sum += (((qq51 & 15) | (((qhq51 >> i) & 1) << 4)) * dq51 + mq51) * vec[block + i];
            sum += (((qq51 >> 4) | (((qhq51 >> (i + 16)) & 1) << 4)) * dq51 + mq51) * vec[block + i + 16];
          }
          total += sum;
        }
        return total;
      case TYPE_Q2_K:
        for (var dq2b = 0; dq2b < cols; dq2b += 256) {
          var dq2base = base + (dq2b / 256) * 84;
          var dq2d = f16(view.getUint16(dq2base + 80, true));
          var dq2min = f16(view.getUint16(dq2base + 82, true));
          var dq2scales = dq2base;
          var dq2qs = dq2base + 16;
          var dq2is = 0;
          var dq2qpos = 0;
          var dq2vpos = dq2b;
          for (var dq2n = 0; dq2n < 256; dq2n += 128) {
            var dq2shift = 0;
            for (var dq2j = 0; dq2j < 4; dq2j += 1) {
              var dq2sc = view.getUint8(dq2scales + dq2is);
              dq2is += 1;
              var dq2dl = dq2d * (dq2sc & 15);
              var dq2ml = dq2min * (dq2sc >> 4);
              for (i = 0; i < 16; i += 1) {
                total += (dq2dl * ((view.getUint8(dq2qs + dq2qpos + i) >> dq2shift) & 3) - dq2ml) * vec[dq2vpos + i];
              }
              dq2vpos += 16;
              var dq2sc2 = view.getUint8(dq2scales + dq2is);
              dq2is += 1;
              var dq2dl2 = dq2d * (dq2sc2 & 15);
              var dq2ml2 = dq2min * (dq2sc2 >> 4);
              for (i = 0; i < 16; i += 1) {
                total += (dq2dl2 * ((view.getUint8(dq2qs + dq2qpos + i + 16) >> dq2shift) & 3) - dq2ml2) * vec[dq2vpos + i];
              }
              dq2vpos += 16;
              dq2shift += 2;
            }
            dq2qpos += 32;
          }
        }
        return total;
      case TYPE_Q3_K:
        for (var dq3b = 0; dq3b < cols; dq3b += 256) {
          var dq3base = base + (dq3b / 256) * 110;
          var dq3d = f16(view.getUint16(dq3base + 108, true));
          var dq3scales = q3Scales(view, dq3base + 96);
          var dq3hm = dq3base;
          var dq3qs = dq3base + 32;
          var dq3m = 1;
          var dq3is = 0;
          var dq3qpos = 0;
          var dq3vpos = dq3b;
          for (var dq3n = 0; dq3n < 256; dq3n += 128) {
            var dq3shift = 0;
            for (var dq3j = 0; dq3j < 4; dq3j += 1) {
              var dq3dl = dq3d * (dq3scales[dq3is] - 32);
              dq3is += 1;
              for (i = 0; i < 16; i += 1) {
                var dq3q = (view.getUint8(dq3qs + dq3qpos + i) >> dq3shift) & 3;
                total += dq3dl * (dq3q - ((view.getUint8(dq3hm + i) & dq3m) ? 0 : 4)) * vec[dq3vpos + i];
              }
              dq3vpos += 16;
              var dq3dl2 = dq3d * (dq3scales[dq3is] - 32);
              dq3is += 1;
              for (i = 0; i < 16; i += 1) {
                var dq3q2 = (view.getUint8(dq3qs + dq3qpos + i + 16) >> dq3shift) & 3;
                total += dq3dl2 * (dq3q2 - ((view.getUint8(dq3hm + i + 16) & dq3m) ? 0 : 4)) * vec[dq3vpos + i];
              }
              dq3vpos += 16;
              dq3shift += 2;
              dq3m <<= 1;
            }
            dq3qpos += 32;
          }
        }
        return total;
      case TYPE_Q5_K:
        for (var dq5b = 0; dq5b < cols; dq5b += 256) {
          var dq5base = base + (dq5b / 256) * 176;
          var dq5d = f16(view.getUint16(dq5base, true));
          var dq5min = f16(view.getUint16(dq5base + 2, true));
          var dq5scales = dq5base + 4;
          var dq5qh = dq5base + 16;
          var dq5qs = dq5base + 48;
          var dq5is = 0;
          var dq5qpos = 0;
          var dq5vpos = dq5b;
          var dq5u1 = 1;
          var dq5u2 = 2;
          for (var dq5j = 0; dq5j < 4; dq5j += 1) {
            var dq5s0 = scaleMinK4(view, dq5scales, dq5is);
            var dq5s1 = scaleMinK4(view, dq5scales, dq5is + 1);
            var dq5d1 = dq5d * dq5s0.d;
            var dq5m1 = dq5min * dq5s0.m;
            var dq5d2 = dq5d * dq5s1.d;
            var dq5m2 = dq5min * dq5s1.m;
            for (i = 0; i < 32; i += 1) {
              var dq5ql = view.getUint8(dq5qs + dq5qpos + i);
              total += (dq5d1 * ((dq5ql & 15) + ((view.getUint8(dq5qh + i) & dq5u1) ? 16 : 0)) - dq5m1) * vec[dq5vpos + i];
            }
            for (i = 0; i < 32; i += 1) {
              var dq5ql2 = view.getUint8(dq5qs + dq5qpos + i);
              total += (dq5d2 * ((dq5ql2 >> 4) + ((view.getUint8(dq5qh + i) & dq5u2) ? 16 : 0)) - dq5m2) * vec[dq5vpos + 32 + i];
            }
            dq5qpos += 32;
            dq5vpos += 64;
            dq5is += 2;
            dq5u1 <<= 2;
            dq5u2 <<= 2;
          }
        }
        return total;
      case TYPE_Q8_K:
        for (var dq8kb = 0; dq8kb < cols; dq8kb += 256) {
          var dq8kbase = base + (dq8kb / 256) * 292;
          var dq8kd = view.getFloat32(dq8kbase, true);
          sum = 0;
          for (i = 0; i < 256; i += 1) sum += view.getInt8(dq8kbase + 4 + i) * vec[dq8kb + i];
          total += dq8kd * sum;
        }
        return total;
      case TYPE_IQ4_NL:
        for (block = 0; block < cols; block += 32) {
          var dnlbase = base + (block / 32) * 18;
          var dnld = f16(view.getUint16(dnlbase, true));
          sum = 0;
          for (i = 0; i < 16; i += 1) {
            var dnlq = view.getUint8(dnlbase + 2 + i);
            sum += IQ4NL[dnlq & 15] * vec[block + i];
            sum += IQ4NL[dnlq >> 4] * vec[block + i + 16];
          }
          total += dnld * sum;
        }
        return total;
      case TYPE_IQ4_XS:
        for (var dxs = 0; dxs < cols; dxs += 256) {
          var dxsbase = base + (dxs / 256) * 136;
          var dxsd = f16(view.getUint16(dxsbase, true));
          var dxsH = view.getUint16(dxsbase + 2, true);
          var dxsL = dxsbase + 4;
          var dxsQ = dxsbase + 8;
          for (var dxsIb = 0; dxsIb < 8; dxsIb += 1) {
            var dxsLs =
              ((view.getUint8(dxsL + (dxsIb >> 1)) >> (4 * (dxsIb & 1))) & 15) |
              (((dxsH >> (2 * dxsIb)) & 3) << 4);
            var dxsDl = dxsd * (dxsLs - 32);
            sum = 0;
            for (i = 0; i < 16; i += 1) {
              var dxq = view.getUint8(dxsQ + dxsIb * 16 + i);
              sum += IQ4NL[dxq & 15] * vec[dxs + dxsIb * 32 + i];
              sum += IQ4NL[dxq >> 4] * vec[dxs + dxsIb * 32 + i + 16];
            }
            total += dxsDl * sum;
          }
        }
        return total;
      case TYPE_IQ2_XXS:
      case TYPE_IQ2_XS:
      case TYPE_IQ2_S:
      case TYPE_IQ3_XXS:
      case TYPE_IQ3_S:
      case TYPE_IQ1_S:
      case TYPE_IQ1_M: {
        var iqBytesD = BLOCK[tensor.type].bytes;
        var iqScratchD = new Float32Array(256);
        for (var qd = 0; qd < cols; qd += 256) {
          iqBlockFloats(tensor.type, view, base + (qd / 256) * iqBytesD, iqScratchD);
          for (i = 0; i < 256; i += 1) total += iqScratchD[i] * vec[qd + i];
        }
        return total;
      }
      case TYPE_BF16:
        for (i = 0; i < cols; i += 1) total += bf16(view.getUint16(base + i * 2, true)) * vec[i];
        return total;
      default:
        throw new Error("cannot dot tensor type " + tensor.type);
    }
  }

