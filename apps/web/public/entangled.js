// third-party API. The weights are the entanglement-spectrum rebuild
// (bond dimension χ=48, 4,673,760 bytes) and the engine is RAREXT's own GGUF
// engine reading its MPO-factored tensors — the same artifact pair a web4
// provider fetches and verifies, now loaded by the browser instead.
//
// Nothing here evaluates an untrusted string: the engine ships VERBATIM as a
// same-origin script (its own tail registers `globalThis.RAREXT_GGUF`), and
// this page verifies BOTH artifacts' sha256 with crypto.subtle before a single
// weight is read. If a byte differs from the digest pinned below, the page
// refuses to run the model.

"use strict";

// The digests the page will serve. Pinned, not discovered: a changed artifact
// is a refusal, not a surprise.
const ENTANGLED_DIGESTS = {
  weights: "da1a69cb75fe0bbfe61f12a4776dc0786d4d0739685e7f79ffac7f8e557cf779",
  engine: "83b666cfe3cf72f32d753c030f258eead72f139a87609b07b6708f4d07933b15",
};

// The engine file is RAREXT's engine VERBATIM: its own tail registers the api
// as `globalThis.RAREXT_GGUF` (and window.RAREXT_GGUF in a browser), so no
// wrapper and no eval are needed — the script tag runs it, and this page only
// has to verify that what was served is byte-for-byte the pinned engine.

async function sha256Hex(bytes) {
  const digest = await crypto.subtle.digest("SHA-256", bytes);
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

/** Load and verify both artifacts, then parse the model. Throws on any digest
 * mismatch — the caller shows the refusal. Works in the browser and, with the
 * bytes handed in directly, under Node for the page's functional test. */
async function loadEntangledModel({ engineSource, weightsBytes }) {
  const engineBytes = new TextEncoder().encode(engineSource);
  const engineDigest = await sha256Hex(engineBytes);
  if (engineDigest !== ENTANGLED_DIGESTS.engine) {
    throw new Error(`engine digest mismatch: got ${engineDigest.slice(0, 16)}…, pinned ${ENTANGLED_DIGESTS.engine.slice(0, 16)}…`);
  }
  const weightsDigest = await sha256Hex(weightsBytes);
  if (weightsDigest !== ENTANGLED_DIGESTS.weights) {
    throw new Error(`weights digest mismatch: got ${weightsDigest.slice(0, 16)}…, pinned ${ENTANGLED_DIGESTS.weights.slice(0, 16)}…`);
  }

  // The engine script registered itself on globalThis when it ran (the page
  // loads it via a script tag before this file). Under the page's Node test
  // there is no script tag: evaluate the EXACT same source, which sets
  // globalThis.RAREXT_GGUF the same way.
  let engine = globalThis.RAREXT_GGUF ?? null;
  if (!engine) {
    new Function(engineSource)();
    engine = globalThis.RAREXT_GGUF ?? null;
  }
  if (!engine || typeof engine.parseGguf !== "function") {
    throw new Error("the verified engine did not register itself (RAREXT_GGUF)");
  }

  const model = { kind: "gguf", bytes: weightsBytes };
  const parsed = engine.parseGguf(model.bytes);
  const factors = Object.keys(parsed.factors ?? {}).length;
  if (factors === 0) {
    throw new Error("the verified weights carry no MPO factor pairs — this page serves the factored rebuild");
  }
  return { engine, model, parsed, factors, digests: { engine: engineDigest, weights: weightsDigest } };
}

function answerWith(engine, model, prompt, steps) {
  const t0 = performance.now();
  const run = engine.run(model, { prompt, steps, temperature: 0 });
  const ms = performance.now() - t0;
  return { text: run.text, tokens: run.tokens.length, ms, finishReason: run.finishReason, cached: run.cachedPromptTokens ?? 0 };
}

