// ---------------------------------------------------------------------------
// The exact numeric tool — deterministic, provable, and the reason the hybrid
// system is exact where the neural model alone is not.
//
// A language model is a next-token predictor; arithmetic over a ledger is not a
// language task, and measuring the χ=48 model alone on held-out numeric prompts
// gives 48% (tools/rank/neural-heldout.json). Frontier systems close that gap
// by calling a calculator. RAREXT does the same, except the tool ships in the
// same 4.6 MB page: parse the ledger, compute with exact integers, format the
// answer. It returns null for anything it does not recognise, and the neural
// model answers those — so the hybrid is never worse, only more exact.
// ---------------------------------------------------------------------------
function parseLedger(prompt) {
  const rows = [];
  const body = String(prompt).replace(/^\s*rows:\s*/i, "");
  for (const line of body.split("\n")) {
    const m = /^\s*-\s*(.+?)\s*\|\s*\$(\d+(?:\.\d+)?)\s*$/.exec(line);
    if (m) rows.push({ name: m[1].trim(), price: Number(m[2]) });
  }
  return rows;
}

function findRow(rows, name) {
  const q = String(name).trim().toLowerCase().replace(/[?.!]+$/, "");
  let hit = rows.find((r) => r.name.toLowerCase() === q);
  if (hit) return hit;
  // tolerate a definite article or extra whitespace the model was not trained on
  hit = rows.find((r) => r.name.toLowerCase() === q.replace(/^(the|a|an)\s+/, ""));
  if (hit) return hit;
  const cands = rows.filter((r) => r.name.toLowerCase().includes(q) || q.includes(r.name.toLowerCase()));
  return cands.length === 1 ? cands[0] : null;
}

const money = (n) => {
  const rounded = Math.round(n * 100) / 100;
  return `$${rounded}`;
};

/** Exact answer for a ledger question, or null when the question is not one of
 * the deterministic families. Pure function: same prompt → same answer, always. */
function answerExact(prompt) {
  const rows = parseLedger(prompt);
  if (!rows.length) return null;
  const q = String(prompt).split(/\nq:\s*/i).pop()?.split(/\na:/i)[0]?.trim() ?? "";
  const lower = q.toLowerCase();

  // how much more is A than B?
  let m = /how much more is (?:the )?(.+?) than (?:the )?(.+?)\?*$/i.exec(q);
  if (m) {
    const a = findRow(rows, m[1]);
    const b = findRow(rows, m[2]);
    if (a && b) return { text: `${money(Math.abs(a.price - b.price))} more`, kind: "diff" };
    return null;
  }

  // total of all items
  if (/total of all|sum of all|total for all/i.test(lower)) {
    const sum = rows.reduce((s, r) => s + r.price, 0);
    return { text: `The total is ${money(sum)} delivered.`, kind: "total" };
  }

  // price after N% off
  m = /after\s+(\d+(?:\.\d+)?)\s*%\s*off/i.exec(q);
  if (m) {
    const pct = Number(m[1]);
    const target = findRow(rows, q.replace(/^.*?(?:the|of)\s+/i, "").replace(/\s+after.*$/i, "")) ?? (rows.length === 1 ? rows[0] : null);
    if (target) {
      const after = Math.round(target.price * (100 - pct)) / 100;
      return { text: `The price is ${money(after)} delivered.`, kind: "pct" };
    }
    return null;
  }

  // cheapest / most expensive
  if (/cheapest|lowest price|least expensive/i.test(lower)) {
    const min = rows.reduce((a, b) => (b.price < a.price ? b : a));
    return { text: `The price is ${money(min.price)} delivered.`, kind: "cheapest" };
  }
  if (/most expensive|priciest|highest price/i.test(lower)) {
    const max = rows.reduce((a, b) => (b.price > a.price ? b : a));
    return { text: `The price is ${money(max.price)} delivered.`, kind: "priciest" };
  }

  // price of a named item — several phrasings
  m = /(?:how much is|what is the price of|what does)\s+(?:the\s+)?(.+?)(?:\s+cost)?\?*$/i.exec(q);
  if (m) {
    const row = findRow(rows, m[1]);
    if (row) return { text: `The price is ${money(row.price)} delivered.`, kind: "lookup" };
    return null;
  }
  if (/^price\?*$/i.test(lower) && rows.length === 1) {
    return { text: `The price is ${money(rows[0].price)} delivered.`, kind: "lookup" };
  }
  return null;
}

// ---------------------------------------------------------------------------
// Holographic memory (FHRR) — the memory axis, in the same tab.
// A phasor vector is a Float32Array of 2D floats: interleaved (re, im) per
// dimension. Binding = complex multiplication (= angle addition); a table is
// the COMPLEX SUM of its bindings (that is the superposition — summing angles
// is the bug that breaks the algebra); recall multiplies by the conjugate cue
// and cleans up by real-dot similarity. Measured properties
// (tools/holographic/hrr.py): capacity scales ~linearly with D, 50% cue
// corruption survives, storage is fixed-size regardless of pair count.
// ---------------------------------------------------------------------------
const HRR_DIM = 4096;

function hrrRandom(d, rng) {
  const v = new Float32Array(2 * d);
  for (let i = 0; i < d; i += 1) {
    const angle = (typeof rng === "function" ? rng() : Math.random()) * 2 * Math.PI;
    v[2 * i] = Math.cos(angle);
    v[2 * i + 1] = Math.sin(angle);
  }
  return v;
}

function hrrBind(a, b) {
  const out = new Float32Array(a.length);
  for (let i = 0; i < a.length; i += 2) {
    out[i] = a[i] * b[i] - a[i + 1] * b[i + 1];
    out[i + 1] = a[i] * b[i + 1] + a[i + 1] * b[i];
  }
  return out;
}

function hrrUnbind(superposition, cue) {
  // multiplication by the conjugate of the cue
  const out = new Float32Array(superposition.length);
  for (let i = 0; i < superposition.length; i += 2) {
    out[i] = superposition[i] * cue[i] + superposition[i + 1] * cue[i + 1];
    out[i + 1] = superposition[i + 1] * cue[i] - superposition[i] * cue[i + 1];
  }
  return out;
}

function hrrSim(z, v) {
  // real part of the complex dot product; unit-norm vectors → cosine
  let sum = 0;
  for (let i = 0; i < z.length; i += 2) sum += z[i] * v[i] + z[i + 1] * v[i + 1];
  return sum / (z.length / 2);
}

function hrrCleanup(z, vocabulary) {
  let bestName = null;
  let bestSim = -2;
  for (const [name, vec] of vocabulary) {
    const sim = hrrSim(z, vec);
    if (sim > bestSim) { bestSim = sim; bestName = name; }
  }
  return { name: bestName, sim: bestSim };
}

/** Encode (item, price) pairs holographically; return a queryable memory.
 * The memory is ONE Float32Array of 2D floats — its byte size does not grow
 * with the number of pairs. Items are names (hashed to a phasor); prices are
 * random phasors cleaned up against the price vocabulary. */
function hrrEncodeTable(pairs, d = HRR_DIM, rng = Math.random) {
  const memory = new Float32Array(2 * d);
  const itemVectors = new Map();
  const priceVectors = new Map();
  for (const [item, price] of pairs) {
    if (!itemVectors.has(item)) itemVectors.set(item, hrrRandom(d, rng));
    if (!priceVectors.has(price)) priceVectors.set(price, hrrRandom(d, rng));
    const binding = hrrBind(itemVectors.get(item), priceVectors.get(price));
    for (let i = 0; i < memory.length; i += 1) memory[i] += binding[i];
  }
  return {
    memory,
    itemVectors,
    priceVectors,
    query(item) {
      const cue = itemVectors.get(item);
      if (cue === undefined) return { price: null, sim: 0 };
      const recovered = hrrUnbind(memory, cue);
      const { name, sim } = hrrCleanup(recovered, priceVectors);
      return { price: name, sim };
    },
    bytes: 2 * d * 4,
  };
}

function hrrSelfTest(pairs, d = HRR_DIM) {
  const memory = hrrEncodeTable(pairs, d);
  let ok = 0;
  const rows = [];
  for (const [item, price] of pairs) {
    const { price: got } = memory.query(item);
    rows.push({ item, want: price, got, ok: got === price });
    ok += got === price;
  }
  return { rows, passed: ok, total: pairs.length, bytes: memory.bytes };
}

// ---------------------------------------------------------------------------
// Holographic DIFFERENCE memory — the arithmetic axis as exact lookup, so the
// combined system (trained model = language + comparison; holographic memory =
// exact numbers) answers questions the trained model alone failed its gate on.
// The cue for an ORDERED pair is the binding of the two item vectors; the
// value is the difference. New pairs are learned by one binding — no gradient
// step, no retraining — which is the holographic answer to skill acquisition.
// ---------------------------------------------------------------------------
function hrrHashVector(name, d) {
  // deterministic phasor from a name: hash bytes → phases, stable per name
  let h1 = 0x9e3779b9, h2 = 0x85ebca6b;
  for (let i = 0; i < name.length; i += 1) {
    h1 = (h1 ^ name.charCodeAt(i)) * 0x85ebca6b; h1 >>>= 0;
    h2 = (h2 ^ name.charCodeAt(name.length - 1 - i)) * 0xc2b2ae35; h2 >>>= 0;
  }
  const v = new Float32Array(2 * d);
  let a = h1 >>> 0, b = h2 >>> 0;
  for (let i = 0; i < d; i += 1) {
    // xorshift-ish mixing so consecutive dimensions decorrelate
    a ^= a << 13; a >>>= 0; a ^= a >> 17; a ^= a << 5; a >>>= 0;
    b ^= b << 7; b >>>= 0; b ^= b >> 9; b ^= b << 3; b >>>= 0;
    const angle = ((a ^ (b * 2654435769)) >>> 0) / 4294967296 * 2 * Math.PI;
    v[2 * i] = Math.cos(angle);
    v[2 * i + 1] = Math.sin(angle);
  }
  return v;
}

/** Encode ordered (a, b) → difference associations. `learn(a, b, diff)` adds
 * one pair with a single binding — instant acquisition, no training. */
function hrrEncodeDifferences(d, valueVocabulary) {
  const memory = new Float32Array(2 * d);
  const itemVectors = new Map();
  const valueVectors = new Map();
  const vecFor = (name) => {
    if (!itemVectors.has(name)) itemVectors.set(name, hrrHashVector(name, d));
    return itemVectors.get(name);
  };
  const valueVec = (value) => {
    if (!valueVectors.has(value)) valueVectors.set(value, hrrRandom(d));
    return valueVectors.get(value);
  };
  for (const v of valueVocabulary) valueVec(v);
  const learned = [];
  const addToMemory = (binding) => {
    for (let i = 0; i < memory.length; i += 1) memory[i] += binding[i];
  };
  return {
    d,
    learned,
    learn(a, b, diff) {
      const cue = hrrBind(vecFor(a), vecFor(b));
      addToMemory(hrrBind(cue, valueVec(diff)));
      learned.push({ a, b, diff });
      return this;
    },
    query(a, b) {
      const va = itemVectors.get(a);
      const vb = itemVectors.get(b);
      if (va === undefined || vb === undefined) return { diff: null, sim: 0 };
      const cue = hrrBind(va, vb);
      const recovered = hrrUnbind(memory, cue);
      const { name, sim } = hrrCleanup(recovered, valueVectors);
      return { diff: name, sim };
    },
    bytes: 2 * d * 4,
  };
}

function hrrDifferenceSelfTest(d = HRR_DIM) {
  // 40 pairs with computed differences, encoded, then every pair queried —
  // plus one brand-new pair learned AFTER encoding (instant acquisition).
  const rows = [];
  const rng = (() => { let s = 987654321; return () => { s = (s * 1103515245 + 12345) % 2147483648; return s / 2147483648; }; })();
  const diffValues = Array.from({ length: 200 }, (_, i) => `$${10 + i * 5} more`);
  const mem = hrrEncodeDifferences(d, diffValues);
  const encodePairs = [];
  for (let i = 0; i < 40; i += 1) {
    const a = `ITEM-${100 + i}`;
    const b = `ITEM-${200 + i}`;
    const diff = `$${10 + ((i * 13) % 190)} more`;
    mem.learn(a, b, diff);
    encodePairs.push({ a, b, diff });
  }
  for (const { a, b, diff } of encodePairs) {
    const { diff: got } = mem.query(a, b);
    rows.push({ a, b, want: diff, got, ok: got === diff });
  }
  const passed = rows.filter((r) => r.ok).length;
  // instant acquisition: a pair the memory never saw, learned now, then asked
  mem.learn("NOVA TEE", "OLD CAP", "$123 more");
  const fresh = mem.query("NOVA TEE", "OLD CAP");
  return {
    rows, passed, total: rows.length, bytes: mem.bytes,
    fresh: { want: "$123 more", got: fresh.diff, ok: fresh.diff === "$123 more" },
  };
}

