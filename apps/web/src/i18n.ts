const dictionaries: Record<Exclude<Locale, "en">, Record<string, string>> = {
  "zh-Hans": zhHans,
  "zh-Hant": zhHant,
  es,
  fr,
  pt,
  ja,
  ar,
};

export const DICTIONARIES: Record<Locale, Record<string, string>> = {
  en,
  ...dictionaries,
};

let active: Locale = "en";

function detect(): Locale {
  const query = new URLSearchParams(window.location.search).get("lang");
  if (query && (LOCALES as readonly string[]).includes(query)) {
    return query as Locale;
  }

  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored && (LOCALES as readonly string[]).includes(stored)) {
    return stored as Locale;
  }

  for (const language of navigator.languages ?? [navigator.language]) {
    const lower = language.toLowerCase();
    if (lower.startsWith("zh")) {
      return /hant|tw|hk|mo/.test(lower) ? "zh-Hant" : "zh-Hans";
    }
    if (lower.startsWith("es")) return "es";
    if (lower.startsWith("fr")) return "fr";
    if (lower.startsWith("pt")) return "pt";
    if (lower.startsWith("ja")) return "ja";
    if (lower.startsWith("ar")) return "ar";
    if (lower.startsWith("en")) return "en";
  }

  return "en";
}

export function t(
  key: string,
  values: Record<string, string | number> = {},
  fallback?: string,
): string {
  const template =
    active === "en"
      ? en[key] ?? fallback ?? key
      : dictionaries[active][key] ?? en[key] ?? fallback ?? key;

  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    values[name] === undefined ? `{${name}}` : String(values[name]),
  );
}

export function getLocale(): Locale {
  return active;
}

export function localeTag(): string {
  return active;
}

export function setLocale(locale: Locale): void {
  window.localStorage.setItem(STORAGE_KEY, locale);
  const url = new URL(window.location.href);
  url.searchParams.set("lang", locale);
  window.location.assign(url.toString());
}

export function initI18n(): void {
  active = detect();
  document.documentElement.lang = active;
  document.documentElement.dir = active === "ar" ? "rtl" : "ltr";
  document.title = t("page.title");

  const description = document.querySelector<HTMLMetaElement>('meta[name="description"]');
  if (description) description.content = t("page.description");

  const select = document.getElementById("locale-select") as HTMLSelectElement | null;
  if (select) {
    select.innerHTML = LOCALES.map(
      (locale) =>
        `<option value="${locale}"${locale === active ? " selected" : ""}>${LOCALE_NAMES[locale]}</option>`,
    ).join("");
    select.setAttribute("aria-label", t("lang"));
    select.addEventListener("change", () => setLocale(select.value as Locale));
  }

  applyTranslations();
}

export function applyTranslations(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n ?? "");
  });

  root.querySelectorAll<HTMLElement>("[data-i18n-placeholder]").forEach((element) => {
    element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder ?? ""));
  });

  root.querySelectorAll<HTMLElement>("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", t(element.dataset.i18nAria ?? ""));
  });

  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((element) => {
    element.setAttribute("title", t(element.dataset.i18nTitle ?? ""));
  });

  root.querySelectorAll<HTMLElement>("[data-i18n-content]").forEach((element) => {
    element.setAttribute("content", t(element.dataset.i18nContent ?? ""));
  });
}
