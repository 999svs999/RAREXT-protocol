#!/usr/bin/env node
/**
 * Generate RAREXT's own-engine IQ grid tables from upstream ggml-common.h.
 *
 *   node scripts/extract-iq-grids.mjs <path/to/ggml-common.h> [engine.js]
 *
 * The tables are the exact numbers ggml ships (iq2xxs_grid, iq2xs_grid,
 * iq2s_grid, iq3xxs_grid, iq3s_grid, iq1s_grid, ksigns_iq2xs, kmask_iq2xs).
 * This script only re-encodes them: every 64-bit/32-bit grid entry becomes its
 * bytes in little-endian order, because that is how ggml reads a row with
 * `(const uint8_t *)(grid + i)`. The engine then needs no BigInt and no
 * endianness assumptions. Only run it to regenerate; the result is committed
 * inside the engine artifact.
 */
import { readFileSync, writeFileSync } from "node:fs";

const headerPath = process.argv[2];
if (headerPath === undefined) {
  console.error("usage: extract-iq-grids.mjs <ggml-common.h> [engine.js]");
  process.exit(1);
}
const enginePath = process.argv[3] ?? "apps/runtime/engines/rarext-gguf-engine.js";
const src = readFileSync(headerPath, "utf8");

const table = (name) => {
  const re = new RegExp(
    `GGML_TABLE_BEGIN\\((\\w+),\\s*${name},\\s*[^)]*\\)([\\s\\S]*?)GGML_TABLE_END\\(\\)`,
  );
  const match = src.match(re);
  if (match === null) throw new Error(`no table named ${name}`);
  const type = match[1];
  const values = match[2]
    .match(/0x[0-9a-fA-F]+|\d+/g)
    .map((text) => BigInt(text));
  return { type, values };
};

const bytesOf = (value, width) => {
  const out = [];
  for (let i = 0; i < width; i += 1) out.push(Number((value >> BigInt(8 * i)) & 0xffn));
  return out;
};

const emit = (name, numbers, arrayType) => {
  const lines = [];
  let line = "  ";
  for (const n of numbers) {
    const piece = `${n},`;
    if (line.length + piece.length > 100) {
      lines.push(line);
      line = "  ";
    }
    line += piece;
  }
  if (line.trim() !== "") lines.push(line);
  return `  var ${name} = new ${arrayType}([\n${lines.join("\n")}\n  ]);`;
};

const u64Bytes = (name) => {
  const { values } = table(name);
  return values.flatMap((value) => bytesOf(value, 8));
};
const u32Bytes = (name) => {
  const { values } = table(name);
  return values.flatMap((value) => bytesOf(value, 4));
};
const signedBytes = (name) => {
  const { values } = table(name);
  return values.flatMap((value) =>
    bytesOf(value, 8).map((byte) => (byte >= 128 ? byte - 256 : byte)),
  );
};

const generated = [
  "  // Generated by scripts/extract-iq-grids.mjs from ggml-common.h.",
  emit("IQ2XXS_GRID", u64Bytes("iq2xxs_grid"), "Uint8Array"),
  emit("IQ2XS_GRID", u64Bytes("iq2xs_grid"), "Uint8Array"),
  emit("IQ2S_GRID", u64Bytes("iq2s_grid"), "Uint8Array"),
  emit("IQ3XXS_GRID", u32Bytes("iq3xxs_grid"), "Uint8Array"),
  emit("IQ3S_GRID", u32Bytes("iq3s_grid"), "Uint8Array"),
  emit("IQ1S_GRID", signedBytes("iq1s_grid"), "Int8Array"),
  emit("KSIGNS_IQ2XS", table("ksigns_iq2xs").values.map(Number), "Uint8Array"),
  emit("KMASK_IQ2XS", table("kmask_iq2xs").values.map(Number), "Uint8Array"),
].join("\n");

const engine = readFileSync(enginePath, "utf8");
const start = "  // __RAREXT_IQ_TABLES_START__";
const end = "  // __RAREXT_IQ_TABLES_END__";
const startAt = engine.indexOf(start);
const endAt = engine.indexOf(end);
if (startAt < 0 || endAt < 0 || endAt < startAt) throw new Error(`markers not found in ${enginePath}`);
const next =
  engine.slice(0, startAt + start.length) +
  "\n" +
  generated +
  "\n" +
  engine.slice(endAt);
writeFileSync(enginePath, next);
console.error(`wrote ${generated.split("\n").length} lines of grid tables into ${enginePath}`);
